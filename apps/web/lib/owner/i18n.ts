const dictionaries: Record<SupportedLocale, OwnerCopy> = { en, et, ru };

export function createOwnerTranslator(locale: SupportedLocale) {
  return function t(
    key: OwnerCopyKey,
    params?: Record<string, string | number>
  ) {
    const raw = dictionaries[locale]?.[key] ?? dictionaries.en[key];
    if (!params) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, k: string) =>
      params[k] !== undefined ? String(params[k]) : `{${k}}`
    );
  };
}

export type OwnerTranslator = ReturnType<typeof createOwnerTranslator>;
export type { OwnerCopyKey };
